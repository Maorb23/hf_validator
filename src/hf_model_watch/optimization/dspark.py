"""Explicit DeepSeek DSpark configuration for the remote optimizer.

Research can discover drafts; only operator compatibility records authorize an
exact target revision, draft revision and immutable worker image for execution.
No GPU support or measured speedup is inferred from a model-card mention.
"""

import json
import re
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

DRAFTS = {
    "Qwen/Qwen3-4B": "deepseek-ai/dspark_qwen3_4b_block7",
    "Qwen/Qwen3-8B": "deepseek-ai/dspark_qwen3_8b_block7",
    "Qwen/Qwen3-14B": "deepseek-ai/dspark_qwen3_14b_block7",
    "google/gemma-4-12B-it": "deepseek-ai/dspark_gemma4_12b_block7",
}


class DSparkConfigurationError(ValueError):
    """Static public errors; no provider content or credentials."""


class Compatibility(BaseModel):
    model_config = ConfigDict(extra="forbid")
    target_model: str
    target_revision: str = Field(pattern=r"^[a-f0-9]{40}$")
    draft_model: str
    draft_revision: str = Field(pattern=r"^[a-f0-9]{40}$")
    runtime: Literal["vllm", "sglang"]
    serving_image: str = Field(pattern=r"^\S+@sha256:[a-f0-9]{64}$")
    # A successful GPU load + benchmark must cover this exact tuple. This is
    # an operator record, never accepted from a browser or generated by an LLM.
    verification_artifact: str = Field(min_length=1, max_length=1000)
    source_urls: list[str] = Field(min_length=1)
    # SGLang uses the immutable draft snapshot baked into the approved image.
    draft_path: str | None = None


def compatibility_records(raw):
    return [Compatibility.model_validate(record) for record in raw]


def capabilities(records, images):
    compatible = []
    for record in compatibility_records(records):
        try:
            resolve(record.target_model, record.target_revision, [record.runtime], images, records)
        except DSparkConfigurationError:
            continue
        compatible.append(
            {
                "target_model": record.target_model,
                "target_revision": record.target_revision,
                "runtime": record.runtime,
            }
        )
    return {"drafts": DRAFTS, "compatible": compatible}


def resolve(model, revision, frameworks, images, records):
    """Fail before research when explicit DSpark cannot execute as requested."""
    if model not in DRAFTS:
        raise DSparkConfigurationError(
            "DeepSeek DSpark has no configured drafter for this target model."
        )
    if any(f not in {"vllm", "sglang"} for f in frameworks):
        raise DSparkConfigurationError(
            "DeepSeek DSpark is available through vLLM or SGLang; deselect TensorRT-LLM."
        )
    arguments, heads = {}, []
    for runtime in frameworks:
        matches = [
            r
            for r in compatibility_records(records)
            if (r.target_model, r.target_revision, r.draft_model, r.runtime, r.serving_image)
            == (model, revision, DRAFTS[model], runtime, images.get(runtime))
        ]
        if len(matches) != 1:
            raise DSparkConfigurationError(
                "DeepSeek DSpark needs one GPU-verified compatibility record "
                "per selected framework "
                "for this exact target revision, drafter revision and worker image. "
                "Ask the operator to configure DSpark compatibility records or choose Auto."
            )
        record = matches[0]
        if runtime == "vllm":
            config = {
                "method": "dspark",
                "model": record.draft_model,
                "revision": record.draft_revision,
                "num_speculative_tokens": 7,
            }
            arguments[runtime] = ["speculative_config=" + repr([json.dumps(config)])]
        else:
            # Paths are part of the immutable image, rather than mutable HF main.
            path = record.draft_path or ""
            if (
                not re.fullmatch(r"/[A-Za-z0-9_./-]+", path)
                or ".." in path.split("/")
                or record.draft_revision not in path.split("/")
            ):
                raise DSparkConfigurationError(
                    "SGLang DSpark requires a pinned draft snapshot "
                    "baked into the verified worker image."
                )
            arguments[runtime] = [
                "speculative_algorithm=['DSPARK']",
                "speculative_draft_model_path=" + repr([path]),
                "speculative_num_draft_tokens=[8]",
                "speculative_num_steps=[1]",
                "speculative_eagle_topk=[1]",
            ]
        heads.append(
            {
                **record.model_dump(),
                "method": "dspark",
                "status": "verified",
                "block_size": 7,
                "execution_status": "configured; not executed in this study",
            }
        )
    return arguments, heads
